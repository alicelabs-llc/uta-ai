#!/usr/bin/env python3
"""Genera la propuesta de /llms.txt v2 para marketnow.site (patrón taiko-docs).

Fuentes VIVAS (números con fecha, regla de oro del agente):
  - sitemap.xml          → rutas indexables
  - /api/skills?limit=1  → total vivo del catálogo
  - /api/agent.json      → versión, checks acumulados, capas

Uso:  python3 generate_llms_txt.py [-o salida.txt]
Salida por defecto: llms-v2.txt (PROPUESTA — revisar antes de reemplazar el
llms.txt actual, que ya es bueno para UTA; ver GAPS.md).
"""
import argparse
import datetime
import json
import re
import urllib.request

UA = {"User-Agent": "uta-ai-llms-generator/1.0 (AliceLabs; +https://marketnow.site)"}
BASE = "https://marketnow.site"
WWW = "https://www.marketnow.site"

# Mapa curado ruta → descripción (mantener a mano; las rutas sin mapa caen en "Other pages")
DESCS = {
    "/": "Home — trust infrastructure for AI agents (SPA)",
    "/registry": "Registry overview — how the catalog is indexed (GitHub, npm, PyPI, MCP Registry, Smithery, crates.io)",
    "/catalog": "Catalog browser — search 71k+ index-certified MCP skills",
    "/submit": "Submit a skill — publish path with Sentinel validation",
    "/pricing": "Pricing — catalog and certification plans",
    "/mandates": "Mandates — signed-intent flow for agent actions (AP2-style)",
    "/trust": "UTA overview — 9 credential formats, 12-stage fail-closed pipeline",
    "/uta": "UTA overview — adapter spec, format matrix, cryptography, roadmap",
    "/standards": "Standards — MCP, A2A, ACP, ATC alignment (LF-AAIF ecosystem)",
    "/listings": "Listings — directory views",
    "/handshake": "Handshake — agent-to-agent trust exchange",
    "/security": "Security hub — 10 layers with per-layer public evidence",
    "/policies": "Policies — catalog, content and trust policies",
    "/dashboard": "Dashboard — maintainer area",
    "/governance": "Governance — decisions, revocations, incident process",
    "/vault": "Vault — key and evidence custody",
    "/compare": "Comparison — MarketNow vs alternatives",
    "/buyers-guide": "Buyers guide — how to evaluate MCP skill marketplaces",
    "/onboarding": "Onboarding — first steps for agents and maintainers",
    "/embed": "Embed — widgets and badges",
    "/agents": "Agent hub — everything an autonomous agent needs in one page",
    "/agent-protocol.json": "Machine spec — agent protocol (JSON)",
    "/acp-spec.json": "Machine spec — ACP (agentic commerce protocol) alignment",
    "/agent-passport-spec.json": "Machine spec — agent passport format",
    "/atc-spec.json": "Machine spec — ATC (Agent Trust Card) format",
    "/about": "About — AliceLabs LLC (Wyoming), founders Edison & Alejandro Flores",
    "/licensing": "License matrix — every component, one table (AL-1.0)",
    "/security/evidence": "Evidence matrix — every security layer mapped to its public artifact",
}


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", default="llms-v2.txt")
    args = ap.parse_args()

    today = datetime.date.today().isoformat()

    # 1. Números vivos
    skills = json.loads(get(f"{WWW}/api/skills?limit=1").decode())
    total = skills["total"]
    agent = json.loads(get(f"{BASE}/api/agent.json").decode())
    version = agent.get("agent", {}).get("version", "unknown")
    checks = agent.get("agent", {}).get("security_checks") or agent.get("capabilities", {}).get("atc", {})

    # 2. Rutas del sitemap
    sm = get(f"{BASE}/sitemap.xml").decode()
    routes = re.findall(r"<loc>([^<]+)</loc>", sm)
    pages = [u.replace(BASE, "") or "/" for u in routes if u.startswith(BASE)]
    html_pages = [p for p in pages if not p.startswith("/api/")]
    api_pages = [p for p in pages if p.startswith("/api/")]

    lines: list[str] = []
    add = lines.append
    add(f"# MarketNow — Universal Trust Adapter & Sentinel catalog (agent index)")
    add("")
    add(f"> Trust infrastructure for AI agents. UTA translates between 9 agent-credential")
    add(f"> formats (ATC v3, JWT/OAuth, W3C VC, A2A Agent Card, EAT-AI, ZTA, MCP Server Card,")
    add(f"> X.509, + bridge) with a fail-closed 12-stage pipeline. Sentinel certifies MCP")
    add(f"> skills: {total:,} index-certified (L1) as of {today} (/api/skills), agent card v{version}.")
    add(f"> Generated by scripts/generate_llms_txt.py from live sources (sitemap + APIs).")
    add("")
    add("## Start here (agents)")
    add("")
    add(f"- {BASE}/SKILL.md — agent reference: how to verify credentials, use the 9 remote MCP tools, and query the catalog")
    add(f"- {BASE}/api/agent.json — full agent card (protocols, tools, discovery well-knowns), v{version}")
    add(f"- {BASE}/.well-known/agent.json — well-known discovery")
    add(f"- {BASE}/.well-known/mcp.json — MCP well-known")
    add(f"- {WWW}/api/trust — Trust API (no auth): verify / translate / issue / bridge; golden rule UNKNOWN=ERROR=EXPIRED=REVOKED=DENY")
    add(f"- {BASE}/api/mcp — remote MCP endpoint (9 tools: search skills, verify trust, translate credential, check domain, fingerprint tool, ...)")
    add("")
    add("## Catalog APIs (no auth)")
    add("")
    add(f"- {WWW}/api/skills — paginated catalog ({total:,} skills as of {today}; sort=recent|downloads|trust|name, q=, risk=, category=, tier=core|community)")
    add(f"- {WWW}/api/categories.json — 16 categories")
    add(f"- {WWW}/api/certification — L1/L2 certification report (methodology + checks)")
    add(f"- {WWW}/api/certification?package=<n> — deep-scan verdict (29-rule L2 subset)")
    add(f"- {WWW}/api/certification-scans.json — raw shasum-verified scan findings")
    add(f"- {WWW}/api/security — security overview, 10 layers with evidence (machine-readable)")
    add(f"- {WWW}/api/security?view=quarantine — tamper-evident quarantine ledger (SHA-256 per record)")
    add(f"- {WWW}/api/sentinel-benchmark.json — decision-level benchmark (precision/recall/F1)")
    add(f"- {BASE}/api/ocsp?kid=<kid> — live OCSP, fail-closed (KEY_COMPROMISE / DENY)")
    add(f"- {WWW}/api/badge/<slug>.svg — embeddable trust badge; {BASE}/s/<slug> — public page per skill")
    add("")
    add("## Agent & protocol surfaces")
    add("")
    for p in ["/agents", "/agent-protocol.json", "/acp-spec.json", "/agent-passport-spec.json", "/atc-spec.json", "/handshake", "/mandates", "/standards"]:
        d = DESCS.get(p, "")
        add(f"- {BASE}{p}{(' — ' + d) if d else ''}")
    add("")
    add("## Pages (sitemap, HTML)")
    add("")
    for p in html_pages:
        d = DESCS.get(p)
        if d:
            add(f"- {BASE}{p} — {d}")
    unmapped = [p for p in html_pages if p not in DESCS]
    if unmapped:
        add("")
        add("## Other pages (auto from sitemap — descriptions pending curation)")
        add("")
        for p in unmapped:
            add(f"- {BASE}{p}")
    add("")
    add("## JSON APIs in sitemap")
    add("")
    for p in api_pages:
        add(f"- {BASE}{p}")
    add("")
    add("## Tools (human-friendly UIs over the APIs)")
    add("")
    add(f"- {WWW}/scam-checker.html — domain risk verdict, heuristics shown")
    add(f"- {WWW}/translate.html — credential translator across the 9 formats")
    add(f"- {WWW}/playground.html — 12-stage verify pipeline, stage by stage")
    add(f"- {BASE}/tools/config-generator.html · /tools/playground.html · /tools/stats.html · /tools/scan.html")
    add("")
    add("## Status & contact")
    add("")
    add("- https://status.marketnow.site/ — live uptime, auto-updated every 5 min (GitHub Actions)")
    add("- https://github.com/alicelabs-llc/universal-trust-adapter — code (AL-1.0)")
    add("- info@alicelabs.site — contact")
    add("")

    out = "\n".join(lines)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"OK {args.out}: {len(lines)} líneas, {len(out)} bytes · total vivo={total:,} · v{version} · {today}")
    print(f"rutas HTML={len(html_pages)} · APIs={len(api_pages)} · sin descripción={len(unmapped)}")
    if checks:
        print(f"checks extras del agent card (revisar curación): {str(checks)[:120]}")


if __name__ == "__main__":
    main()
